#!/usr/bin/env python3
"""sources/transcripts/*.md -> site/data/transcripts.js (run from repo root).

Redactions: Sridhar's sensitive sentence is already removed at source (never restore it).
Prabhakar's cut-off last line is dropped here. PJN gets a "write-up, not word-for-word" note.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "sources", "transcripts")
OUT = os.path.join(ROOT, "site", "data", "transcripts.js")

MAP = {
    "gopi": ("P-GOPI", "Interview with Mr. Gopi"),
    "sln-shastry": ("P-SLN", "Interview with SLN Shastry"),
    "pj-narayanan-dossier": ("P-PJN", "Interview dossier: Prof. P. J. Narayanan"),
    "ks-rajan-notes": ("P-RAJAN", "Interview notes: Prof. K. S. Rajan"),
    "muralidhar-librarian": ("P-MURALI", "Interview with G. Muralidhar"),
    "prabhakar-m": ("P-PRAB", "Interview with Prabhakar M"),
    "sridhar-kora": ("P-SRIDHAR", "Interview with Sridhar Kora"),
}

NOTES = {
    "P-PJN": "This is a write-up of the interview, not a word-for-word transcript. It was polished by a tool after the interview, so the facts are his but the fancy wording is not. We only paraphrase it.",
    "P-RAJAN": "These are notes made from an automatic transcript of a 21-minute recording. Items marked [unclear] still need checking against the audio.",
    "P-SRIDHAR": "One sentence was removed by the team for privacy.",
    "P-PRAB": "The original file ends mid-sentence. We left that last line out.",
}


def norm(s):
    s = s.replace("—", ", ").replace("–", "-").replace("‘", "'").replace("’", "'")
    s = s.replace("“", '"').replace("”", '"').replace("→", "to").replace("•", "-")
    s = s.replace("⚠️", "Note:").replace("⚠", "Note:")
    return s


def paragraphs(text):
    """Re-flow hard-wrapped lines into paragraphs; keep headings, bullets and table rows on their own lines."""
    lines = text.split("\n")
    out, buf = [], []

    def flush():
        if buf:
            out.append(" ".join(x.strip() for x in buf))
            buf.clear()

    for ln in lines:
        s = ln.rstrip()
        if not s.strip():
            flush()
            continue
        st = s.strip()
        if st.startswith(("#", "- ", "* ", "|", ">")) or re.match(r"^\d+\.\s", st) or re.match(r"^[A-Z0-9 .&:()'-]{6,}$", st):
            flush()
            out.append(st)
        else:
            buf.append(s)
    flush()
    return out


def main():
    data = {}
    for slug, (pid, title) in MAP.items():
        raw = open(os.path.join(SRC, slug + ".md"), encoding="utf-8").read()
        m = re.search(r"Source file: `([^`]+)`", raw)
        source_file = m.group(1) if m else None
        # drop the first heading and the source-file blockquote
        body = re.sub(r"^# .*\n", "", raw, count=1)
        body = re.sub(r"^> Source file:.*\n", "", body, flags=re.M)
        if pid == "P-PRAB":
            body = body.replace("The program Women in provided housing for the girls inside the new\nParijat hostel as well the year it was made", "")
        if pid == "P-PJN":
            body = re.sub(r"P U B L I C H I S TO RY.*\n", "", body)
            body = re.sub(r"Public History Archives .*Page \d of 4\n?", "", body)
        paras = [norm(p) for p in paragraphs(body)]
        paras = [p for p in paras if p and p not in ("Full transcript:",)]
        data[pid] = {"title": title, "sourceFile": source_file, "note": NOTES.get(pid), "paras": paras}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/gen_transcripts_js.py from sources/transcripts/*.md. Do not edit by hand. */\n")
        f.write("window.M = window.M || {};\nM.transcripts = ")
        f.write(json.dumps(data, indent=1, ensure_ascii=False))
        f.write(";\n")
    print("transcripts.js:", {k: len(v["paras"]) for k, v in data.items()})


if __name__ == "__main__":
    main()
