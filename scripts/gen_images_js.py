#!/usr/bin/env python3
"""raw/photos/captions.json -> site/data/images.js (run from repo root)."""
import glob, json, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAP = os.path.join(ROOT, "raw", "photos", "captions.json")
FULL = os.path.join(ROOT, "site", "assets", "photos", "full")
OUT = os.path.join(ROOT, "site", "data", "images.js")

FIXES = {
    "The back in the day photo of the road to and from OBH.": "An early photo of the road to and from OBH.",
    "Early photo of obh with still young banyan tree": "Early photo of OBH with a still young banyan tree.",
    "The room former Director Narendra Ahuja used in guest house": "The guest house room that the first Director, Prof. Narendra Ahuja, used.",
    "Gopi's room in guest house where the phone booth used to be": "Gopi's room in the guest house, where the phone booth used to be.",
    "Guest house lobby where the mess used to be in the early days of IIIT": "The guest house lobby, where the mess used to be in the early days of IIIT.",
}

# Short section keys for grouping in the archive.
SECTION_KEYS = {
    "Archival stills: early campus (from IIITH's 20-year video)": "early",
    "Satellite imagery: how parts of campus changed": "satellite",
    "Corporate schools": "corporate",
    "Guest house": "guesthouse",
    "Saranga Hall": "saranga",
    "Abandoned civil engineering department": "civil",
    "Campus artefacts": "artefacts",
}


def clean(s):
    if s is None:
        return None
    s = s.replace("—", ", ").replace("–", "-").replace("‘", "'").replace("’", "'")
    s = s.replace("“", '"').replace("”", '"')
    s = FIXES.get(s, s)
    s = s.strip()
    if s and s[-1] not in ".!?\"'…)":
        s += "."
    return s


def dims(path):
    try:
        with Image.open(path) as im:
            return im.size
    except Exception:
        return (0, 0)


def main():
    caps = json.load(open(CAP))
    out = []
    for c in caps:
        n = c["id"]
        base = os.path.splitext(c["file"])[0] + ".jpg"
        w, h = dims(os.path.join(FULL, base))
        out.append({
            "id": "img-%02d" % n, "n": n,
            "file": "assets/photos/full/" + base, "thumb": "assets/photos/thumb/" + base,
            "w": w, "h": h,
            "caption": clean(c["caption"]),
            "section": c["section"].replace("–", "-"), "group": SECTION_KEYS.get(c["section"], "other"),
            "tags": c.get("tags", []), "notes": clean(c.get("notes")),
            "source": "S-PHOTOS",
        })
    x = os.path.join(FULL, "x01_saranga-hall-2.jpg")
    if os.path.exists(x):
        w, h = dims(x)
        out.append({"id": "img-x01", "n": 101, "file": "assets/photos/full/x01_saranga-hall-2.jpg",
                    "thumb": "assets/photos/thumb/x01_saranga-hall-2.jpg", "w": w, "h": h,
                    "caption": "Saranga Hall, the past library, now a lecture hall.",
                    "section": "Saranga Hall", "group": "saranga", "tags": ["Saranga Hall", "library"],
                    "notes": None, "source": "S-PHOTOS"})
    for p in sorted(glob.glob(os.path.join(FULL, "c[0-9][0-9]_civil-uncaptioned.jpg"))):
        k = int(os.path.basename(p)[1:3])
        w, h = dims(p)
        b = os.path.basename(p)
        out.append({"id": "img-c%02d" % k, "n": 200 + k, "file": "assets/photos/full/" + b,
                    "thumb": "assets/photos/thumb/" + b, "w": w, "h": h,
                    "caption": "Uncaptioned, from the civil department visit, 28 Oct 2026.",
                    "section": "Civil department visit (uncaptioned)", "group": "civilraw",
                    "tags": ["civil engineering", "uncaptioned"], "notes": None, "source": "S-CIVILRAW"})
    with open(OUT, "w") as f:
        f.write("/* Generated by scripts/gen_images_js.py from raw/photos/captions.json. Do not edit by hand. */\n")
        f.write("window.M = window.M || {};\nM.images = ")
        f.write(json.dumps(out, indent=1, ensure_ascii=False))
        f.write(";\n")
    print("images.js:", len(out), "images")


if __name__ == "__main__":
    main()
